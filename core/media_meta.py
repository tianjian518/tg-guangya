def _tmdb_key() -> str:
    """读 TMDB api_key。带进程内缓存——旧实现每条标题都 reload 一次配置文件。"""
    global _tmdb_key_cache
    if _tmdb_key_cache is None:
        try:
            from core.config import AppConfig
            from core.data_dir import resolve_config_path
            _tmdb_key_cache = (AppConfig.load(str(resolve_config_path())).tmdb.api_key or "").strip()
        except Exception:
            _tmdb_key_cache = ""
    return _tmdb_key_cache


_tmdb_key_cache: str | None = None


def _tmdb_search(query: str, kind: str, key: str) -> dict | None:
    """查 TMDB 的 /search/movie 或 /search/tv，返回命中的第一条。"""
    url = (
        f"https://api.themoviedb.org/3/search/{kind}"
        f"?query={urllib.parse.quote(query)}&language=zh-CN&api_key={key}"
    )
    req = urllib.request.Request(url, headers={"User-Agent": "tg-guangya/1.6"})
    with urllib.request.urlopen(req, timeout=6) as resp:
        data = json.loads(resp.read())
    for r in data.get("results") or []:
        title = (r.get("title") or r.get("name") or "").strip()
        if not title:
            continue
        return {
            "cn_name": title,
            "original_language": (r.get("original_language") or "").strip(),
            "year": int(((r.get("release_date") or r.get("first_air_date") or "")[:4] or 0) or 0),
            "source": "tmdb",
        }
    return None


def _tmdb_lookup(query: str, year: int = 0) -> dict | None:
    """先按电影查，再按剧集查（追剧资源以前查不到就是漏了 tv）。"""
    key = _tmdb_key()
    if not key or not query:
        return None
    global _fail_count, _fail_until
    if time.time() < _fail_until:
        return None
    for kind in ("movie", "tv"):
        try:
            hit = _tmdb_search(query, kind, key)
        except Exception:
            _fail_count += 1
            if _fail_count >= _FAIL_LIMIT:
                _fail_until = time.time() + _FAIL_COOLDOWN
                _fail_count = 0
            continue
        # 年份对不上可接受——TMDB 首个结果未必精确，但译名通常是对的
        if hit:
            _fail_count = 0
            return hit
    return None


# ---------------------------------------------------------------- 对外入口
def lookup(title: str, year: int = 0) -> MediaMeta:
    """查一条英文片名的中文译名与原始语言。查不到返回空 MediaMeta。

    :param title: 尽量干净的英文片名（调用方应已剥掉分辨率/编码等噪声）
    :param year:  已知年份，可提升 TMDB 命中率（当前仅用于缓存键）
    """
    if not title or _CJK.search(title):
        return MediaMeta()  # 已经是中文，不需要翻译
    key = f"{normalize_en(title)}|{year or 0}"
    if not key.strip("|"):
        return MediaMeta()

    with _lock:
        hit = _mem_cache.get(key)
        if hit is not None:
            return MediaMeta(**hit)
        _load_disk_cache()
        hit = _disk_cache.get(key)
        if hit is not None:
            _mem_cache[key] = hit
            return MediaMeta(**hit)

        out: dict = {}
        norm = normalize_en(title)

        # 1. 用户自定义字典（用户自己加的，优先级最高）
        ud = _load_user_dict()
        if norm in ud:
            out = {"cn_name": ud[norm], "original_language": "",
                   "year": 0, "region": BUILTIN_REGION.get(norm, ""),
                   "source": "user_dict"}

        # 2. 内置字典精确匹配（带 the 前缀的片名再试一次去掉 the 的形式）
        if not out:
            for cand in (norm, _THE.sub("", norm)):
                if cand and cand in _NORM_DICT:
                    out = {"cn_name": _NORM_DICT[cand], "original_language": "",
                           "year": 0, "region": BUILTIN_REGION.get(cand, ""),
                           "source": "dict"}
                    break

        # 3. 内置短语包含匹配
        if not out:
            for phrase, cn in _NORM_PHRASES:
                if len(phrase) >= 5 and phrase in norm:
                    out = {"cn_name": cn, "original_language": "",
                           "year": 0, "region": BUILTIN_REGION.get(phrase, ""),
                           "source": "dict"}
                    break

        # 4. TMDB（唯一能给出 original_language 的来源）
        if not out or not out.get("region") or not out.get("original_language"):
            tm = _tmdb_lookup(title, year)
            if tm:
                tm["region"] = language_to_region(tm.get("original_language", ""))
                # 本地字典已有译名时，只借用 TMDB 的地区与年份
                if out.get("cn_name"):
                    out["original_language"] = tm.get("original_language", "")
                    out["region"] = out.get("region") or tm.get("region", "")
                    if not out.get("year"):
                        out["year"] = tm.get("year", 0)
                    out["source"] += "+tmdb"
                else:
                    out = tm

        if not out:
            out = {"cn_name": "", "original_language": "", "year": 0,
                   "region": "", "source": ""}

        _mem_cache[key] = out
        _disk_cache[key] = out
        # 每个新查询都落盘代价太高，攒够 20 条或每 10 条写一次
        if len(_disk_cache) % 10 == 0:
            _save_disk_cache()
        return MediaMeta(**out)


def translate(title: str, year: int = 0) -> str:
    """只要译名。查不到返回空串（调用方应保留英文原名）。"""
    return lookup(title, year).cn_name


def language_to_region(lang: str) -> str:
    """TMDB 的 original_language → 本项目地区码。

    这是地区判定里最权威的一路：TMDB 直接告诉你这片子原创语言是什么，
    比靠标题里的「国语/英语」标签猜要准得多。
    """
    lang = (lang or "").lower()
    if lang in ("zh", "cn", "yue", "cmn", "wuu", "nan"):
        return "cn"
    if lang in ("ja", "ko"):
        return "jpkr"
    if lang in ("en", "fr", "de", "es", "it", "ru", "pt", "nl", "sv", "no", "da", "fi", "pl"):
        return "west"
    if lang in ("th", "vi", "id", "ms", "hi", "ta", "te", "tr", "fa", "ar"):
        return "other"
    return ""


def flush() -> None:
    """把内存缓存写回磁盘（进程退出前调用）。"""
    with _lock:
        _save_disk_cache()


def stats() -> dict:
    with _lock:
        _load_disk_cache()
        return {
            "builtin_entries": len(_NORM_DICT),
            "phrases": len(_NORM_PHRASES),
            "cached": len(_disk_cache),
            "tmdb_enabled": bool(_tmdb_key()),
        }
