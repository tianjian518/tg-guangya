def normalize_en(s: str) -> str:
    """英文片名归一化：小写 + 去掉空格/点/连字符/下划线/撇号。

    "The.Wandering.Earth.II" / "the wandering earth ii" → "thewanderingearthii"
    """
    return re.sub(r"[\s\.\-_'’]+", "", (s or "").lower())


